class Command(BaseCommand):
    help = "Seeds 18 progressive 3-stage Ghanaian clinical cases across all 6 nursing programmes."

    @transaction.atomic
    def handle(self, *args, **options):
        created_cases = 0
        for case_data in CLINICAL_CASES_DATA:
            course = Course.objects.filter(program=case_data["program"], is_published=True).first()
            case, created = ClinicalCase.objects.get_or_create(
                title=case_data["title"],
                defaults={
                    "course": course,
                    "condition_tag": case_data["condition_tag"],
                    "setting": case_data["setting"],
                    "difficulty": case_data["difficulty"],
                    "patient_summary": case_data["patient_summary"],
                    "learning_objectives": case_data["learning_objectives"],
                    "is_published": True,
                },
            )
            if created:
                created_cases += 1
            for stage in case_data["stages"]:
                CaseStage.objects.update_or_create(
                    case=case,
                    step_number=stage["step_number"],
                    defaults={
                        "title": stage["title"],
                        "vitals_summary": stage["vitals_summary"],
                        "clinical_update": stage["clinical_update"],
                        "question_prompt": stage["question_prompt"],
                        "options": stage["options"],
                        "rationale": stage["rationale"],
                        "nursing_takeaway": stage["nursing_takeaway"],
                    },
                )

        self.stdout.write(
            self.style.SUCCESS(
                f"Done! Seeded {created_cases} new clinical cases (total {len(CLINICAL_CASES_DATA)} cases, 54 stages across all 6 programmes)."
            )
        )
created = updated = 0
for code, label, domain, definition, dc, rf in NANDA:
    obj, is_new = NandaDiagnosis.objects.update_or_create(
        code=code,
        defaults={
            'label': label,
            'domain': domain,
            'definition': definition,
            'defining_characteristics': dc,
            'related_factors': rf,
            'edition_year': 2021,
            'is_active': True,
        }
    )
    if is_new: created += 1
    else: updated += 1

print(f"✅ NANDA seeded: {created} created, {updated} updated")
print(f"   Total in DB: {NandaDiagnosis.objects.count()}")
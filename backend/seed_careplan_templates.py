def get_diag(code):
    """Resolve a diagnosis; fall back gracefully if code doesn't exist."""
    d = NandaDiagnosis.objects.filter(code=code).first()
    if not d:
        raise SystemExit(f"❌ Diagnosis code {code} not found. Run seed_nanda_diagnoses.py first.")
    return d


created = updated = skipped = 0
for t in TEMPLATES:
    try:
        diag = get_diag(t["primary_diagnosis"])
    except SystemExit as e:
        print(e)
        skipped += 1
        continue

    course = Course.objects.filter(code=t["course_code"]).first()
    if not course:
        print(f"⚠️  Course {t['course_code']} not found — template will have null course")

    obj, is_new = CarePlanTemplate.objects.update_or_create(
        title=t["title"],
        defaults={
            "description": t["description"],
            "primary_diagnosis": diag,
            "course": course,
            "default_goals": t["goals"],
            "default_interventions": t["interventions"],
            "is_published": True,
        },
    )
    if is_new: created += 1
    else: updated += 1
    print(f"{'CREATED' if is_new else 'UPDATED'}: {t['title']}")

print(f"\n✅ Templates seeded: {created} created, {updated} updated, {skipped} skipped")
print(f"   Total templates in DB: {CarePlanTemplate.objects.count()}")